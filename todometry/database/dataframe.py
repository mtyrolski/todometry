ADJUSTMENTS_VARIABLE_NAME = "link_adjustements"
DEFAULT_ADJUSTMENTS_FILENAME = "archived_root_projects.py"


class ProjectIdRule(TypedDict):
    targetId: str
    targetName: str


class ProjectAdjustments(NamedTuple):
    mappings: dict[str, str]
    archived_parents: list[str]
    project_mappings: dict[str, ProjectIdRule]


def parse_project_id_mappings(value: object) -> dict[str, ProjectIdRule]:
    if not isinstance(value, dict):
        raise TypeError("projectMappings must be an object keyed by project ID.")
    rules: dict[str, ProjectIdRule] = {}
    for source_id, target in value.items():
        if (
            not isinstance(source_id, str)
            or not source_id.strip()
            or not isinstance(target, dict)
        ):
            raise TypeError("Each project mapping requires a source ID and target.")
        target_id, target_name = target.get("targetId"), target.get("targetName")
        if (
            not isinstance(target_id, str)
            or not target_id.strip()
            or not isinstance(target_name, str)
            or not target_name.strip()
        ):
            raise TypeError("Each project mapping requires a target ID and name.")
        rules[source_id] = {"targetId": target_id, "targetName": target_name}
    return rules


def resolve_personal_dir() -> Path:
    override = os.getenv(str(EnvVar.PERSONAL_DIR))
    if override:
        return Path(override).expanduser().resolve()
    return (Path.cwd() / "personal").resolve()


def normalize_adjustment_filename(filename: str) -> str:
    candidate = filename.strip()
    if not candidate:
        raise ValueError("Adjustment file name is required")
    if Path(candidate).name != candidate:
        raise ValueError("Adjustment file name must not include path separators")
    if Path(candidate).suffix != ".py":
        raise ValueError("Adjustment file name must end with .py")
    if candidate.startswith(".") or candidate in {".", ".."}:
        raise ValueError("Adjustment file name must be a simple filename")
    return candidate


def render_adjustments_file_content(
    mappings: dict[str, str],
    archived_parents: list[str] | None = None,
    project_mappings: dict[str, ProjectIdRule] | None = None,
) -> str:
    archived_parents = archived_parents or []
    sorted_mappings = dict(sorted(mappings.items(), key=lambda item: item[0]))
    sorted_archived_parents = sorted(set(archived_parents))
    content = [
        "# Local project adjustments",
        "# This file was generated by the web dashboard admin UI",
        "",
        f"{ADJUSTMENTS_VARIABLE_NAME} = {pformat(sorted_mappings, sort_dicts=True)}",
        "",
        f"archived_parent_projects = {pformat(sorted_archived_parents)}",
    ]
    if project_mappings:
        content.append(
            f"project_id_mappings = {pformat(project_mappings, sort_dicts=True)}"
        )
    return "\n".join(content) + "\n"


def _load_adjustments_literal_file(path: Path) -> ProjectAdjustments:
    try:
        raw_text = path.read_text(encoding="utf-8")
    except OSError as exc:
        raise ValueError(f"Unable to read adjustment file: {path.name}") from exc

    try:
        module = ast.parse(raw_text, filename=str(path))
    except SyntaxError as exc:
        raise ValueError(f"Invalid adjustment file syntax: {path.name}") from exc

    mapping: dict[str, str] | None = None
    archived_parents: list[str] | None = None
    project_mappings: dict[str, ProjectIdRule] = {}
    for node in module.body:
        if (
            isinstance(node, ast.Expr)
            and isinstance(node.value, ast.Constant)
            and isinstance(node.value.value, str)
        ):
            continue
        if not isinstance(node, ast.Assign):
            raise ValueError(
                "Adjustment files may only contain literal assignments and comments"
            )
        if len(node.targets) != 1 or not isinstance(node.targets[0], ast.Name):
            raise ValueError("Unsupported adjustment assignment")
        target_name = node.targets[0].id
        try:
            value = ast.literal_eval(node.value)
        except (ValueError, SyntaxError) as exc:
            raise ValueError(
                f"Adjustment file contains non-literal values: {path.name}"
            ) from exc
        if target_name == ADJUSTMENTS_VARIABLE_NAME:
            if not isinstance(value, dict) or not all(
                isinstance(key, str) and isinstance(val, str)
                for key, val in value.items()
            ):
                raise TypeError(
                    f'"{ADJUSTMENTS_VARIABLE_NAME}" in {path.name} must be a string-to-string dict'
                )
            mapping = dict(value)
        elif target_name == "archived_parent_projects":
            if not isinstance(value, list) or not all(
                isinstance(item, str) for item in value
            ):
                raise TypeError(
                    f'"archived_parent_projects" in {path.name} must be a list of strings'
                )
            archived_parents = list(value)
        elif target_name == "project_id_mappings":
            project_mappings = parse_project_id_mappings(value)

    return ProjectAdjustments(mapping or {}, archived_parents or [], project_mappings)


def load_adjustments_file(filename: str | Path) -> ProjectAdjustments:
    path = Path(filename)
    if path.suffix != ".py":
        raise ValueError("Adjustment files must use the .py extension")
    return _load_adjustments_literal_file(path)


def _adjustment_paths(personal_dir: Path, specific_file: str | None) -> list[Path]:
    if specific_file:
        safe_specific = normalize_adjustment_filename(specific_file)
        logger.info(f"Loading specific mapping file: {safe_specific}")
        path = personal_dir / safe_specific
        return [path] if path.exists() else []
    paths = [
        path
        for path in sorted(personal_dir.iterdir())
        if path.is_file() and path.suffix == ".py"
    ]
    logger.info(f"Found {len(paths)} scripts in personal directory")
    return paths


def load_project_adjustments(specific_file: str | None = None) -> ProjectAdjustments:
    """Load the saved project rules in mapping-file order."""
    personal_dir = resolve_personal_dir()
    if not personal_dir.exists():
        return ProjectAdjustments({}, [], {})

    mapping: dict[str, str] = {}
    archived_parent_projects: set[str] = set()
    project_mappings: dict[str, ProjectIdRule] = {}
    for path in _adjustment_paths(personal_dir, specific_file):
        rules = load_adjustments_file(path)
        mapping.update(rules.mappings)
        archived_parent_projects.update(rules.archived_parents)
        project_mappings.update(rules.project_mappings)
    return ProjectAdjustments(
        mapping, sorted(archived_parent_projects), project_mappings
    )


class ProjectGroup(NamedTuple):
    """Analytical group, including the original root ID for unresolved aliases."""

    root_id: str
    name: str
    alias: str | None = None


class ProjectHierarchy(NamedTuple):
    """Project metadata, effective parents and report groups from one resolution."""

    original_parents: dict[str, str | None]
    parents: dict[str, str | None]
    assignments: dict[str, str]
    groups: dict[str, ProjectGroup]
    legacy_target_ids: dict[str, str]
    adjusted_projects: set[str]
    explicit_roots: set[str]
    promoted_roots: set[str]
    labels: dict[str, str]


def _todoist_parent(project: Project) -> str | None:
    parent = project.project_entry.parent_id or project.project_entry.v2_parent_id
    return str(parent) if parent else None


def project_lineage(project_id: str, parents: dict[str, str | None]) -> Iterator[str]:
    """Yield the project and its successive known parents."""
    current: str | None = project_id
    visited: set[str] = set()
    while current is not None and current not in visited:
        visited.add(current)
        yield current
        current = parents.get(current)


def _physical_parents(
    projects: dict[str, Project], original_roots: dict[str, Project]
) -> dict[str, str | None]:
    parents: dict[str, str | None] = dict.fromkeys(projects)
    for project_id, project in sorted(projects.items()):
        parent = _todoist_parent(project)
        if parent not in projects:
            root = original_roots.get(project_id)
            parent = str(root.id) if root is not None else None
        if parent is not None and project_id not in project_lineage(parent, parents):
            parents[project_id] = parent
    return parents


def _legacy_targets(projects: dict[str, Project], promoted: set[str]) -> dict[str, str]:
    """Resolve old names by preferring known roots and then active projects."""
    by_name: dict[str, list[str]] = defaultdict(list)
    for project_id, project in projects.items():
        by_name[project.project_entry.name].append(project_id)

    targets: dict[str, str] = {}
    for name, ids in by_name.items():
        roots = [
            project_id
            for project_id in ids
            if _todoist_parent(projects[project_id]) is None or project_id in promoted
        ]
        candidates = roots or ids
        active = [
            project_id
            for project_id in candidates
            if not projects[project_id].is_archived
        ]
        preferred = active or candidates
        if len(preferred) == 1:
            targets[name] = preferred[0]
    return targets


def resolve_project_hierarchy(
    projects: dict[str, Project],
    adjustments: ProjectAdjustments | None = None,
    *,
    original_roots: dict[str, Project] | None = None,
) -> ProjectHierarchy:
    """Resolve saved rules once for hierarchy, timelines and activity grouping.

    Archived parent buckets take precedence over legacy name mappings on their
    descendants. Elsewhere those mappings apply to archived nodes or physical
    roots. A valid ID rule takes priority on its own project, and descendants
    follow the resulting hierarchy. Missing or ambiguous legacy targets keep
    their configured label without attaching the branch to a guessed project.
    """
    adjustments = adjustments or ProjectAdjustments({}, [], {})
    original_roots = original_roots or {}
    projects = {**{str(root.id): root for root in original_roots.values()}, **projects}
    original_parents = _physical_parents(projects, original_roots)
    parents = original_parents.copy()
    promoted_names = set(adjustments.archived_parents)
    promoted = {
        project_id
        for project_id, project in projects.items()
        if project.is_archived and project.project_entry.name in promoted_names
    }
    id_targets = {
        source: rule["targetId"]
        for source, rule in adjustments.project_mappings.items()
        if source in projects and rule["targetId"] in projects
    }
    explicit_roots = {
        source for source, target in id_targets.items() if source == target
    }
    assignments: dict[str, str] = {}
    applied = promoted.copy()
    for project_id, project in projects.items():
        if project_id in explicit_roots:
            parents[project_id] = None
            assignments[project_id] = "Main project"
        elif project_id in promoted:
            parents[project_id] = None
            assignments[project_id] = "Manual parent bucket"
        elif parents[project_id] is None:
            assignments[project_id] = (
                "Archived root" if project.is_archived else "Root project"
            )
        else:
            assignments[project_id] = (
                "Automatic (Todoist hierarchy)"
                if project.is_archived
                else "Todoist hierarchy"
            )

    legacy_target_ids = _legacy_targets(projects, promoted)
    legacy_aliases: dict[str, ProjectGroup] = {}
    linked_targets: set[str] = set()
    for project_id, project in sorted(projects.items()):
        name = project.project_entry.name
        target_name = adjustments.mappings.get(name)
        if (
            target_name is None
            or project_id in id_targets
            or name in promoted_names
            or (not project.is_archived and original_parents[project_id] is not None)
        ):
            continue
        original_lineage = list(project_lineage(project_id, original_parents))
        if promoted.intersection(original_lineage):
            continue

        # A legacy self-name masks an inherited rename and keeps the recorded parent.
        target_id = legacy_target_ids.get(target_name)
        if target_name == name or target_id is None:
            legacy_aliases[project_id] = ProjectGroup(
                original_lineage[-1], target_name, target_name
            )
            assignments[project_id] = "Manual mapping"
        elif project_id not in project_lineage(target_id, parents):
            parents[project_id] = target_id
            assignments[project_id] = "Manual mapping"
            applied.add(project_id)
            linked_targets.add(target_id)

    applied_id_rules = explicit_roots.copy()
    for source, target in sorted(id_targets.items()):
        if source != target and source not in project_lineage(target, parents):
            parents[source] = target
            assignments[source] = "Manual mapping"
            applied_id_rules.add(source)
    applied.update(applied_id_rules)

    names = {
        project_id: project.project_entry.name
        for project_id, project in projects.items()
    }
    name_counts = Counter(names.values())
    # Give other same-named projects distinct labels while retaining resolved legacy labels.
    labels = {
        project_id: f"{name} · {project_id}"
        if name_counts[name] > 1 and project_id not in linked_targets
        else name
        for project_id, name in names.items()
    }
    groups: dict[str, ProjectGroup] = {}
    adjusted_projects: set[str] = set()
    for project_id in projects:
        lineage = list(project_lineage(project_id, parents))
        alias = next(
            (legacy_aliases[node] for node in lineage if node in legacy_aliases), None
        )
        if alias is not None or applied.intersection(lineage):
            adjusted_projects.add(project_id)

        root_id = lineage[-1]
        if alias is not None and not applied_id_rules.intersection(lineage):
            root_id = alias.root_id
            if alias.name != names[root_id]:
                groups[project_id] = alias
                continue

        groups[project_id] = ProjectGroup(root_id, labels[root_id])
    for project_id, root in original_roots.items():
        groups.setdefault(project_id, groups[str(root.id)])

    return ProjectHierarchy(
        original_parents=original_parents,
        parents=parents,
        assignments=assignments,
        groups=groups,
        legacy_target_ids=legacy_target_ids,
        adjusted_projects=adjusted_projects,
        explicit_roots=explicit_roots,
        promoted_roots={
            project_id for project_id in promoted if parents[project_id] is None
        },
        labels=labels,
    )


def apply_project_groups(
    activity: pd.DataFrame, hierarchy: ProjectHierarchy
) -> pd.DataFrame:
    """Apply current analytical groups while retaining unknown cached assignments."""
    if "parent_project_id" not in activity or not hierarchy.groups:
        return activity
    project_ids = cast(pd.Series, activity["parent_project_id"].astype(str))
    root_ids = project_ids.map(
        {project_id: group.root_id for project_id, group in hierarchy.groups.items()}
    )
    root_names = project_ids.map(
        {project_id: group.name for project_id, group in hierarchy.groups.items()}
    )
    return activity.assign(
        root_project_id=root_ids.fillna(activity.get("root_project_id", project_ids)),
        root_project_name=root_names.fillna(
            activity.get(
                "root_project_name", activity.get("parent_project_name", "(unknown)")
            )
        ),
    )


def load_cached_activity_data(
    active_projects: list[Project],
    archived_projects: list[Project],
    *,
    cache: Cache | None = None,
    hierarchy: ProjectHierarchy | None = None,
) -> pd.DataFrame:
    """Rebuild activity from local events and previously saved project metadata."""
    return _activity_dataframe(
        _load_events(cache), active_projects, archived_projects, hierarchy=hierarchy
    )


def load_activity_data(
    db: DatabaseProjects,
    *,
    cache: Cache | None = None,
    hierarchy: ProjectHierarchy | None = None,
) -> pd.DataFrame:
    """Load activity with project metadata, recovering unknown roots when online."""
    activity = _load_events(cache)
    original_roots = db.fetch_mapping_project_id_to_root() if hierarchy is None else None
    return _activity_dataframe(
        activity,
        db.fetch_projects(include_tasks=False),
        db.fetch_archived_projects(),
        hierarchy=hierarchy,
        original_roots=original_roots,
    )


def _load_events(cache: Cache | None) -> set[Event]:
    return load_valid_events((cache or Cache()).activity.load())


def _activity_dataframe(
    activity: set[Event],
    active_projects: list[Project],
    archived_projects: list[Project],
    *,
    hierarchy: ProjectHierarchy | None = None,
    original_roots: dict[str, Project] | None = None,
) -> pd.DataFrame:
    projects = {
        str(project.id): project for project in (*archived_projects, *active_projects)
    }
    hierarchy = hierarchy or resolve_project_hierarchy(
        projects, load_project_adjustments(), original_roots=original_roots
    )
    df = events_to_dataframe(
        activity,
        project_id_to_name={
            project_id: project.project_entry.name
            for project_id, project in projects.items()
        },
        project_id_to_root=original_roots or {},
    )
    df = apply_project_groups(df, hierarchy)
    df["date"] = pd.to_datetime(df["date"], utc=True)
    df.sort_values("date", inplace=True)
    df["id"] = df["id"].astype(str)
    df["root_project_id"] = df["root_project_id"].astype(str)
    return df
